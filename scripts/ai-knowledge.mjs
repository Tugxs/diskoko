export function selectAiKnowledge(prompt, context = []) {
  const text = [prompt, ...context.filter(item => item?.role === 'user').slice(-2).map(item => item.content)].join(' ');
  const selected = playbooks.filter(item => item.match.test(text)).slice(0, 3);
  return [(selected.length ? selected : []).map(item => item.text).join('\n'),expertContext(prompt,context),designIdeaKnowledge(text)].filter(Boolean).join('\n');
}

