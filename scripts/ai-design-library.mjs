export function selectDesignIdeas(prompt) {
  const words=String(prompt||'').toLowerCase().split(/[^\p{L}\p{N}]+/u).filter(word=>word.length>2);
  return designIdeas.map(item=>({item,score:words.reduce((score,word)=>score+Number(`${item.titleAr} ${item.titleEn} ${item.category} ${item.route}`.toLowerCase().includes(word)),0)})).filter(entry=>entry.score>0).sort((a,b)=>b.score-a.score).slice(0,5).map(entry=>entry.item);
}
export function designIdeaKnowledge(prompt) {
  const selected=selectDesignIdeas(prompt);
  if (!selected.length) return '';
  return 'Optional ideas, not new tools: '+selected.map(item=>`${item.titleAr} / ${item.titleEn}: ${item.route} (${item.availability})`).join('; ')+'. Never claim a development idea is ready. Existing editors require opening their existing library form. Compose only currently supported functions; ask for essential missing details.';
}
